/**
 * regen-cli-templates.mjs — the CLI template map's authoring tool
 * (4.0.0). Reads the two shipped template components
 * (playground/templates/*.tsx), applies the EXACT escape transform
 * (`trimEnd` + backslash/backtick/${ escapes), prepends the CLI
 * generated-file header and rebuilds the PAGE_TEMPLATES entries of
 * bin/templates.mjs verbatim. The file header + the htmlSource
 * static mirrors live in this script (they are the hand-authored
 * half); the tsxSource payloads are mechanical.
 *
 * Run after ANY edit to playground/templates/*.tsx:
 *   node scripts/regen-cli-templates.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const target = resolve(root, "bin", "templates.mjs");

/** The exact (tpl1)/(tpl3) transform — drift here is drift in the gate. */
function escapeTemplate(source) {
  return source
    .trimEnd()
    .replace(/\\/g, "\\\\")
    .replace(/`/g, "\\`")
    .replace(/\$\{/g, "\\${");
}

/** The CLI generated-file header prepended to every tsxSource. */
function cliHeader(label, marker, slug) {
  return `/**
 * Signature${marker} — the Signature Style ${label} full-page template.
 * Generated by @carcolacha/signature-style init (template: ${slug}).
 *
 * PREREQ — install the engine and import the css bundle ONCE in your
 * entry, BEFORE your own styles:
 *   npm i @carcolacha/signature-style
 *   import "@carcolacha/signature-style/css";
 *
 * The template is SELF-CONTAINED: one default-export page composed
 * from @carcolacha/signature-style/react exports, carrying its own
 * embedded <style> block (token-driven — it paints with the
 * signature-tokens.css variables; container queries make it answer
 * its container width, reduced-motion is honored).
 */
`;
}


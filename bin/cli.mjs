/**
 * Render the resolved single-theme tokens file for the chosen theme.
 *
 * @param {string} themeName - one of THEME_NAMES
 * @returns {string} the file content
 */
function renderTokensCss(themeName) {
  const resolved = resolveThemeTokens(themeName);
  const header = `/* ==========================================================================
   SIGNATURE STYLE — signature-tokens.css
   generated by ${PKG} init — theme: ${themeName}
   regenerate via: npx ${PKG} init --theme ${themeName} --force

   One resolved :root for "${THEMES[themeName].label}". The full package's
   [data-sig-theme] runtime triad lives in css/signature-style.css — a
   scaffold bakes its chosen theme in; switch themes by regenerating
   (--theme oled|daylight --force) or install ${PKG} for runtime switching.

   Geometry: the "standard" preset is baked in (8px UI / 12px cards,
   8px-grid-pure). RULE OF ENGAGEMENT: --sig-* tokens are CONTENT accents
   only (badges, tags, data-viz) — structural UI keeps Flamingo/Teal
   (--color-cake-*). Never crossed.
   ========================================================================== */`;
  const body = Object.entries(resolved)
    .map(([key, value]) => `  ${key}: ${value};`)
    .join("\n");
  return `${header}\n\n:root {\n${body}\n}\n`;
}


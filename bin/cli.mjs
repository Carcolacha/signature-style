/**
 * Run the init flow: resolve the target dir, prompt when interactive,
 * detect, plan, inject, summarize.
 *
 * @param {ReturnType<typeof parseArgv>} opts
 * @returns {Promise<void>}
 */
async function runInit(opts) {
  if (!isAbsolute(opts.dir)) opts.dir = resolve(process.cwd(), opts.dir);
  const targetDir = resolve(opts.dir);

  const rl = isInteractive() && !opts.yes ? createInterface({ input: process.stdin, output: process.stdout }) : null;
  try {
    if (rl) {
      const ask = makeAsker(rl);
      if (!opts.explicit.has("theme")) opts.theme = await promptChoice(ask, "Theme", THEME_NAMES, opts.theme);
      if (!opts.explicit.has("template")) opts.template = await promptChoice(ask, "Template", TEMPLATE_NAMES, opts.template);
      const proceed = await promptConfirmDir(ask, targetDir);
      if (!proceed) {
        process.stdout.write("Aborted — nothing written.\n");
        return;
      }
    }

    if (!existsSync(targetDir)) mkdirSync(targetDir, { recursive: true });

    const detection = detectFramework(targetDir);
    process.stdout.write(`\u2192 detected framework: ${detection.label} (${detection.reason})\n`);
    process.stdout.write(`\u2192 theme: ${opts.theme} \u00b7 template: ${opts.template}\n\n`);

    injectFiles(buildFiles(opts, detection), targetDir, opts.force);
    printSummary(opts, detection, targetDir);
  } finally {
    if (rl) rl.close();
  }
}

/** Entry: parse, dispatch, and map every failure to a clean exit 1. */
async function runCli() {
  const opts = parseArgv(process.argv.slice(2));
  if (opts.help) {
    printUsage(process.stdout);
    return;
  }
  if (opts.command !== "init") {
    throw new CliError(`unknown command "${opts.command ?? "(none)"}" — usage: npx ${PKG} init --help`);
  }
  await runInit(opts);
}

runCli().catch((err) => {
  process.stderr.write(`\u2717 ${err instanceof Error ? err.message : String(err)}\n`);
  process.exitCode = 1;
});

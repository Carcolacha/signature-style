/**
 * Detect the host project in targetDir and pick the bento starter flavor.
 *
 * @param {string} targetDir
 * @returns {{label: string, starter: "tsx"|"html", reason: string}}
 */
function detectFramework(targetDir) {
  const entries = existsSync(targetDir) ? readdirSync(targetDir) : [];
  const visible = entries.filter((entry) => !entry.startsWith("."));
  const hasViteConfig = entries.some((entry) => /^vite\.config\.(ts|mts|tsx|js|mjs|jsx|cjs)$/.test(entry));
  const hasViteDep = hasDependency(targetDir, "vite");
  if (hasViteConfig) return { label: "vite-react", starter: "tsx", reason: "vite.config found" };
  if (hasViteDep) return { label: "vite-react", starter: "tsx", reason: "vite in package.json dependencies" };
  if (entries.some((entry) => /^next\.config\.(js|mjs|ts|mts|cjs)$/.test(entry))) {
    return { label: "next", starter: "tsx", reason: "next.config found" };
  }
  if (visible.includes("index.html")) return { label: "html", starter: "html", reason: "index.html found" };
  if (visible.length === 0) return { label: "fresh", starter: "html", reason: "empty directory" };
  return { label: "html", starter: "html", reason: "no framework markers — universal html starter" };
}

/**
 * Read deps+devDeps from targetDir/package.json (tolerant: absent or
 * unparseable package.json simply means no dependency match).
 *
 * @param {string} targetDir
 * @param {string} name
 * @returns {boolean}
 */
function hasDependency(targetDir, name) {
  const pkgPath = join(targetDir, "package.json");
  if (!existsSync(pkgPath)) return false;
  try {
    const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
    return Boolean((pkg.dependencies && pkg.dependencies[name]) || (pkg.devDependencies && pkg.devDependencies[name]));
  } catch {
    return false; // malformed package.json must never crash the scaffold
  }
}


/** @returns {boolean} true when both streams are a real terminal */
function isInteractive() {
  return Boolean(process.stdout.isTTY && process.stdin.isTTY);
}

/**
 * A race-proof line source over one readline interface. `rl.question` has
 * a hole: lines arriving BETWEEN two questions fire as `line` events with
 * no listener and are lost, leaving the next prompt waiting on a closed
 * stream. This queue pins one persistent `line` listener — every answer is
 * kept, first-in-first-out — and EOF resolves pending reads as "" so the
 * prompt layer degrades to defaults instead of hanging.
 *
 * @param {import("node:readline").Interface} rl
 * @returns {(promptText: string) => Promise<string>} ask one question
 */
function makeAsker(rl) {
  const buffered = [];
  const waiting = [];
  rl.on("line", (line) => {
    const resolveNext = waiting.shift();
    if (resolveNext) resolveNext(line);
    else buffered.push(line);
  });
  rl.on("close", () => {
    while (waiting.length > 0) waiting.shift()("");
  });
  return async (promptText) => {
    process.stdout.write(promptText);
    if (buffered.length > 0) return buffered.shift();
    return new Promise((resolveNext) => waiting.push(resolveNext));
  };
}

/**
 * Ask until a valid choice (or the default on empty input).
 *
 * @param {ReturnType<typeof makeAsker>} ask
 * @param {string} label
 * @param {string[]} valid
 * @param {string} def
 * @returns {Promise<string>}
 */
async function promptChoice(ask, label, valid, def) {
  for (;;) {
    const answer = String(await ask(`${label} [${valid.join("/")}] (${def}): `)).trim().toLowerCase();
    if (answer === "") return def;
    if (valid.includes(answer)) return answer;
    process.stdout.write(`  ? "${answer}" is not one of ${valid.join(", ")} — try again\n`);
  }
}

/**
 * Ask a yes/no confirmation (empty = yes).
 *
 * @param {ReturnType<typeof makeAsker>} ask
 * @param {string} dir
 * @returns {Promise<boolean>}
 */
async function promptConfirmDir(ask, dir) {
  for (;;) {
    const answer = String(await ask(`Scaffold into ${dir}? [Y/n]: `)).trim().toLowerCase();
    if (answer === "" || answer === "y" || answer === "yes") return true;
    if (answer === "n" || answer === "no") return false;
    process.stdout.write(`  ? answer "y" or "n"\n`);
  }
}


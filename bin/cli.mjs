/**
 * Hand-rolled argv parser for the CLI contract.
 *
 * @param {string[]} args - process.argv.slice(2)
 * @returns {{command: string|null, template: string, theme: string, dir: string, force: boolean, yes: boolean, help: boolean, explicit: Set<string>}}
 */
function parseArgv(args) {
  const opts = {
    command: null,
    template: "minimal",
    theme: "mocha",
    dir: process.cwd(),
    force: false,
    yes: false,
    help: false,
    explicit: new Set(),
  };
  for (let i = 0; i < args.length; i++) {
    const arg = args[i];
    switch (arg) {
      case "init":
        if (opts.command !== null) throw new CliError(`unexpected second command "${arg}"`);
        opts.command = "init";
        break;
      case "--template":
        opts.template = takeValue(args, ++i, arg);
        if (!TEMPLATE_NAMES.includes(opts.template)) {
          throw new CliError(`invalid --template "${opts.template}" — expected one of ${TEMPLATE_NAMES.join(", ")}`);
        }
        opts.explicit.add("template");
        break;
      case "--theme":
        opts.theme = takeValue(args, ++i, arg);
        if (!THEME_NAMES.includes(opts.theme)) {
          throw new CliError(`invalid --theme "${opts.theme}" — expected one of ${THEME_NAMES.join(", ")}`);
        }
        opts.explicit.add("theme");
        break;
      case "--dir":
        opts.dir = takeValue(args, ++i, arg);
        opts.explicit.add("dir");
        break;
      case "--force":
        opts.force = true;
        break;
      case "--yes":
        opts.yes = true;
        break;
      case "--help":
      case "-h":
        opts.help = true;
        break;
      default:
        if (arg.startsWith("-")) {
          throw new CliError(`unknown flag "${arg}" — run "npx ${PKG} init --help"`);
        }
        if (opts.command !== null) {
          throw new CliError(`unexpected argument "${arg}" — run "npx ${PKG} init --help"`);
        }
        opts.command = arg;
    }
  }
  return opts;
}

/**
 * Pull the value after a value-flag, erroring when absent.
 *
 * @param {string[]} args
 * @param {number} index - index of the candidate value
 * @param {string} flag - the flag name (for the error message)
 * @returns {string}
 */
function takeValue(args, index, flag) {
  const value = args[index];
  if (value === undefined || value.startsWith("--")) {
    throw new CliError(`flag ${flag} requires a value — e.g. ${flag} bento`);
  }
  return value;
}

